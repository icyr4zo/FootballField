-- Schema theo mục 3.2 của báo cáo (đầy đủ PK/FK/UNIQUE/CHECK/ENUM)
CREATE TABLE ca_lam (
  ma_ca         INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ten_ca        VARCHAR(30)  NOT NULL,
  gio_bat_dau   TIME         NOT NULL,
  gio_ket_thuc  TIME         NOT NULL,
  luong_theo_ca DECIMAL(12,0) NOT NULL,
  PRIMARY KEY (ma_ca),
  CONSTRAINT uq_ca_lam_ten UNIQUE (ten_ca),
  CONSTRAINT ck_ca_gio   CHECK (gio_bat_dau <> gio_ket_thuc),
  CONSTRAINT ck_ca_luong CHECK (luong_theo_ca >= 0)
) ENGINE=InnoDB;

CREATE TABLE nhan_vien (
  ma_nv          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ho_ten         VARCHAR(100) NOT NULL,
  so_dien_thoai  VARCHAR(10)  NOT NULL,
  ngay_sinh      DATE         NOT NULL,
  ma_ca          INT UNSIGNED NOT NULL,
  PRIMARY KEY (ma_nv),
  CONSTRAINT uq_nv_sdt UNIQUE (so_dien_thoai),
  CONSTRAINT ck_nv_sdt CHECK (so_dien_thoai REGEXP '^0[0-9]{9}$'),
  CONSTRAINT fk_nv_ca FOREIGN KEY (ma_ca) REFERENCES ca_lam (ma_ca)
    ON UPDATE CASCADE ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE khach_hang (
  ma_kh          INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ho_ten         VARCHAR(100) NOT NULL,
  so_dien_thoai  VARCHAR(10)  NOT NULL,
  email          VARCHAR(100) NULL,
  tong_diem      INT UNSIGNED NOT NULL DEFAULT 0,
  cap_bac        ENUM('Bronze Member','Silver Member','Gold Member')
                 NOT NULL DEFAULT 'Bronze Member',
  PRIMARY KEY (ma_kh),
  CONSTRAINT uq_kh_sdt UNIQUE (so_dien_thoai),
  CONSTRAINT ck_kh_sdt CHECK (so_dien_thoai REGEXP '^0[0-9]{9}$'),
  CONSTRAINT ck_kh_cap_bac CHECK (
       (tong_diem < 50  AND cap_bac = 'Bronze Member')
    OR (tong_diem BETWEEN 50 AND 149 AND cap_bac = 'Silver Member')
    OR (tong_diem >= 150 AND cap_bac = 'Gold Member'))
) ENGINE=InnoDB;

CREATE TABLE san_bong (
  ma_san      INT UNSIGNED NOT NULL AUTO_INCREMENT,
  tinh_trang  ENUM('trống','đang cho thuê') NOT NULL DEFAULT 'trống',
  PRIMARY KEY (ma_san)
) ENGINE=InnoDB;

CREATE TABLE khung_gio_gia (
  ma_khung_gio  INT UNSIGNED NOT NULL AUTO_INCREMENT,
  gio_bat_dau   TIME         NOT NULL,
  gio_ket_thuc  TIME         NOT NULL,
  don_gia_gio   DECIMAL(12,0) NOT NULL,
  PRIMARY KEY (ma_khung_gio),
  CONSTRAINT uq_khung_bat_dau UNIQUE (gio_bat_dau),
  CONSTRAINT ck_khung_gio CHECK (gio_bat_dau <> gio_ket_thuc),
  CONSTRAINT ck_khung_gia CHECK (don_gia_gio > 0)
) ENGINE=InnoDB;

CREATE TABLE dich_vu (
  ma_dv    INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ten_dv   VARCHAR(50)  NOT NULL,
  don_gia  DECIMAL(12,0) NOT NULL,
  PRIMARY KEY (ma_dv),
  CONSTRAINT uq_dv_ten UNIQUE (ten_dv),
  CONSTRAINT ck_dv_gia CHECK (don_gia >= 0)
) ENGINE=InnoDB;

CREATE TABLE luot_dat_san (
  ma_dat_san         INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ma_san             INT UNSIGNED NOT NULL,
  ma_kh              INT UNSIGNED NOT NULL,
  ma_nv_tiep_nhan    INT UNSIGNED NOT NULL,
  thoi_diem_tao      DATETIME     NOT NULL,
  thoi_gian_bat_dau  DATETIME     NOT NULL,
  thoi_gian_ket_thuc DATETIME     NOT NULL,
  tong_tien_san      DECIMAL(12,0) NOT NULL DEFAULT 0,
  hinh_thuc_thue     ENUM('đặt trước','thuê trực tiếp tại quầy') NOT NULL,
  trang_thai         ENUM('đã đặt','đang chơi','đã hủy','đã hoàn thành')
                     NOT NULL DEFAULT 'đã đặt',
  tien_coc           DECIMAL(12,0) NOT NULL DEFAULT 0,
  phuong_thuc_coc    ENUM('tiền mặt','chuyển khoản','quẹt thẻ') NULL,
  PRIMARY KEY (ma_dat_san),
  CONSTRAINT fk_ld_san FOREIGN KEY (ma_san) REFERENCES san_bong (ma_san)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_ld_kh FOREIGN KEY (ma_kh) REFERENCES khach_hang (ma_kh)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_ld_nv FOREIGN KEY (ma_nv_tiep_nhan) REFERENCES nhan_vien (ma_nv)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT ck_ld_gio_tron CHECK (
        MINUTE(thoi_gian_bat_dau) = 0 AND SECOND(thoi_gian_bat_dau) = 0
    AND MINUTE(thoi_gian_ket_thuc) = 0 AND SECOND(thoi_gian_ket_thuc) = 0),
  CONSTRAINT ck_ld_thoi_luong CHECK (
        TIMESTAMPDIFF(HOUR, thoi_gian_bat_dau, thoi_gian_ket_thuc) BETWEEN 1 AND 3),
  CONSTRAINT ck_ld_khong_lui CHECK (thoi_gian_bat_dau > thoi_diem_tao),
  CONSTRAINT ck_ld_tien CHECK (tong_tien_san >= 0 AND tien_coc >= 0
                               AND tien_coc <= tong_tien_san),
  CONSTRAINT ck_ld_coc CHECK (
       (hinh_thuc_thue = 'thuê trực tiếp tại quầy' AND tien_coc = 0 AND phuong_thuc_coc IS NULL)
    OR (hinh_thuc_thue = 'đặt trước' AND phuong_thuc_coc IS NOT NULL)),
  INDEX idx_ld_san_tg (ma_san, thoi_gian_bat_dau, thoi_gian_ket_thuc),
  INDEX idx_ld_kh (ma_kh),
  INDEX idx_ld_trang_thai (trang_thai, thoi_gian_bat_dau)
) ENGINE=InnoDB;

CREATE TABLE chi_tiet_gia_san (
  ma_dat_san       INT UNSIGNED NOT NULL,
  gio_thue         DATETIME     NOT NULL,
  ma_khung_gio     INT UNSIGNED NOT NULL,
  don_gia_ap_dung  DECIMAL(12,0) NOT NULL,
  PRIMARY KEY (ma_dat_san, gio_thue),
  CONSTRAINT fk_ctgs_ld FOREIGN KEY (ma_dat_san) REFERENCES luot_dat_san (ma_dat_san)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_ctgs_khung FOREIGN KEY (ma_khung_gio) REFERENCES khung_gio_gia (ma_khung_gio)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT ck_ctgs_gio CHECK (MINUTE(gio_thue) = 0 AND SECOND(gio_thue) = 0),
  CONSTRAINT ck_ctgs_gia CHECK (don_gia_ap_dung > 0)
) ENGINE=InnoDB;

CREATE TABLE chi_tiet_dich_vu (
  ma_dat_san  INT UNSIGNED NOT NULL,
  ma_dv       INT UNSIGNED NOT NULL,
  so_luong    INT UNSIGNED NOT NULL,
  don_gia     DECIMAL(12,0) NOT NULL,
  thanh_tien  DECIMAL(12,0) NOT NULL,
  PRIMARY KEY (ma_dat_san, ma_dv),
  CONSTRAINT fk_ctdv_ld FOREIGN KEY (ma_dat_san) REFERENCES luot_dat_san (ma_dat_san)
    ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_ctdv_dv FOREIGN KEY (ma_dv) REFERENCES dich_vu (ma_dv)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT ck_ctdv_sl   CHECK (so_luong > 0),
  CONSTRAINT ck_ctdv_gia  CHECK (don_gia >= 0),
  CONSTRAINT ck_ctdv_tien CHECK (thanh_tien = so_luong * don_gia)
) ENGINE=InnoDB;

CREATE TABLE hoa_don (
  ma_hd                   INT UNSIGNED NOT NULL AUTO_INCREMENT,
  ma_dat_san              INT UNSIGNED NOT NULL,
  ma_nv_lap               INT UNSIGNED NOT NULL,
  thoi_diem_lap           DATETIME     NOT NULL,
  phuong_thuc_thanh_toan  ENUM('tiền mặt','chuyển khoản','quẹt thẻ') NOT NULL,
  tien_san                DECIMAL(12,0) NOT NULL,
  tien_giam_gia           DECIMAL(12,0) NOT NULL DEFAULT 0,
  tien_coc_da_tru         DECIMAL(12,0) NOT NULL DEFAULT 0,
  tien_dich_vu            DECIMAL(12,0) NOT NULL DEFAULT 0,
  so_tien_phai_tra        DECIMAL(12,0) NOT NULL,
  PRIMARY KEY (ma_hd),
  CONSTRAINT uq_hd_luot UNIQUE (ma_dat_san),
  CONSTRAINT fk_hd_ld FOREIGN KEY (ma_dat_san) REFERENCES luot_dat_san (ma_dat_san)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_hd_nv FOREIGN KEY (ma_nv_lap) REFERENCES nhan_vien (ma_nv)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT ck_hd_tien CHECK (tien_san >= 0 AND tien_giam_gia >= 0
        AND tien_coc_da_tru >= 0 AND tien_dich_vu >= 0 AND so_tien_phai_tra >= 0),
  CONSTRAINT ck_hd_phai_tra CHECK (
        so_tien_phai_tra = tien_san - tien_giam_gia - tien_coc_da_tru + tien_dich_vu),
  INDEX idx_hd_thoi_diem (thoi_diem_lap)
) ENGINE=InnoDB;

